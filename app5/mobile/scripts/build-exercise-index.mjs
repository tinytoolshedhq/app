import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const base = path.join(root, "assets/exercises");
function walk(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((e) =>
      e.isDirectory()
        ? walk(path.join(dir, e.name))
        : e.name === "exercise.json"
          ? [path.join(dir, e.name)]
          : [],
    );
}
const files = walk(base).sort();
const imports = [],
  rows = [],
  audios = [],
  listing = [],
  ids = new Set();
for (const [i, file] of files.entries()) {
  const ex = JSON.parse(fs.readFileSync(file, "utf8"));
  if (ids.has(ex.id)) throw new Error(`重複動作 ID: ${ex.id}`);
  ids.add(ex.id);
  if (ex.duration_seconds !== 30) throw new Error(`${ex.id}: 必須為 30 秒`);
  const rel = path
    .relative(path.join(root, "src/content"), file)
    .split(path.sep)
    .join("/");
  imports.push(`import ex${i} from ${JSON.stringify(rel)};`);
  rows.push(`ex${i}`);
  listing.push(
    `- ${ex.library.body_part} / ${ex.library.muscle} / ${ex.name} (${ex.id})\n  ${ex.description}\n  語音：${ex.voice_cues.map((c) => `${c.at_seconds}s「${c.text}」`).join("；")}`,
  );
  const cues = ex.voice_cues;
  for (const [j, c] of cues.entries()) {
    if (
      c.at_seconds < 0 ||
      c.at_seconds + c.max_duration_seconds > (cues[j + 1]?.at_seconds ?? 30)
    )
      throw new Error(`${c.id}: 語音超出時間窗`);
    if (!c.audio_path) continue;
    const audio = path.resolve(path.dirname(file), c.audio_path);
    if (!audio.startsWith(path.dirname(file) + path.sep))
      throw new Error(`${c.id}: 音檔超出動作資料夾`);
    if (fs.existsSync(audio)) {
      if (
        c.audio_status !== "ready" ||
        !(c.measured_duration_seconds > 0) ||
        c.measured_duration_seconds > c.max_duration_seconds
      )
        throw new Error(`${c.id}: 音檔需標記 ready 並填入符合上限的實測秒數`);
      audios.push(
        `${JSON.stringify(c.id)}: require(${JSON.stringify(path.relative(path.join(root, "src/content"), audio).split(path.sep).join("/"))})`,
      );
    } else if (c.audio_status === "ready")
      throw new Error(`${c.id}: ready 音檔不存在`);
  }
}
fs.writeFileSync(
  path.join(root, "src/content/exercise-index.ts"),
  `// Generated by npm run content:build. Edit assets/exercises instead.\n${imports.join("\n")}\nexport const exerciseLibrary = [${rows.join(", ")}];\nexport const cueAssets: Record<string, number> = {${audios.join(",\n")}};\n`,
);
fs.writeFileSync(
  path.join(base, "動作清單.txt"),
  `伸展動作庫：${files.length} 個內容單位，每個 30 秒\n以下含同一活動的姿勢變體，並非全部都是靜態伸展。\n\n${listing.join("\n\n")}\n`,
);
console.log(
  `Indexed ${files.length} exercises, ${audios.length} ready voice clips.`,
);
