import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const directory = path.join(root, "assets/figma");
const assets = {};
for (const name of fs
  .readdirSync(directory)
  .filter((name) => name.endsWith(".svg"))
  .sort()) {
  const svg = fs.readFileSync(path.join(directory, name), "utf8");
  if (
    !/<svg\b/.test(svg) ||
    !/viewBox=/.test(svg) ||
    !/width="\d/.test(svg) ||
    !/height="\d/.test(svg)
  )
    throw new Error(`${name}: SVG root dimensions missing`);
  if (/https?:\/\/(?!www\.w3\.org\/)/.test(svg))
    throw new Error(`${name}: external resource not allowed`);
  assets[path.basename(name, ".svg").replaceAll("-", "_")] = svg;
}
fs.writeFileSync(
  path.join(root, "src/components/figmaAssets.ts"),
  `// Generated by npm run assets:build from the approved local Figma SVG files.\nexport const figmaAssets = ${JSON.stringify(assets, null, 2)};\n`,
);
console.log(`Bundled ${Object.keys(assets).length} local Figma SVG assets.`);
